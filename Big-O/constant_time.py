## O(1) — Constant Time

# O(1) means the algorithm performs a constant amount of work, 
# regardless of the input size.
# O(1) is considered one of the most efficient time complexities because 
# the operation does not depend on the input size.

def get_first(numbers):
  return numbers[0]

print(get_first([10, 3, 5, 7])) # 10
